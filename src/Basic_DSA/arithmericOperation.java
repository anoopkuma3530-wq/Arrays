package Basic_DSA;

public class arithmericOperation {
    public static void main(String[] args) {
        double x=5;
        double y=2;
        System.out.println(x+y);
        System.out.println(x-y);
        System.out.println(x*y);
        System.out.println(x/y);
        System.out.println(x%2);
    }
}
